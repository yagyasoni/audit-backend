    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    article_id TEXT UNIQUE NOT NULL,

    title TEXT NOT NULL,
    category TEXT DEFAULT 'General',

    content TEXT NOT NULL,

    status TEXT NOT NULL
    CHECK (status IN ('Published', 'Draft'))
